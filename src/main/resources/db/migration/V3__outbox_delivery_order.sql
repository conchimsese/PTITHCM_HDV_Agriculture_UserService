-- Enforce queue order per account/channel without coupling Kafka delivery to SMTP.
ALTER TABLE outbox ADD COLUMN delivery_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY;
-- Preserve the deterministic historical order for rows written before this migration.
WITH ordered AS (
    SELECT event_id, row_number() OVER (ORDER BY created_at, event_id) AS position FROM outbox
)
UPDATE outbox SET delivery_sequence=ordered.position FROM ordered WHERE outbox.event_id=ordered.event_id;
SELECT setval(pg_get_serial_sequence('outbox','delivery_sequence'),
              COALESCE((SELECT max(delivery_sequence) FROM outbox),0)+1, false);
ALTER TABLE outbox ALTER COLUMN delivery_sequence SET GENERATED ALWAYS;
CREATE UNIQUE INDEX outbox_sequence_idx ON outbox (delivery_sequence);
CREATE INDEX outbox_aggregate_pending_idx
    ON outbox (aggregate_id, channel, delivery_sequence)
    WHERE published_at IS NULL;
